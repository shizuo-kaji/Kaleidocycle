"""Vendor manifold-3d for Kaleidocycle Studio as a classic script.

The studio runs from ``file://`` without a server, so it cannot import ES
modules or fetch a neighbouring ``.wasm`` file.  This script takes the
``manifold.js`` (an Emscripten ES module) and ``manifold.wasm`` of the npm
package ``manifold-3d``, and writes ``web/vendor/manifold-classic.js``:

- ``import.meta.url`` is replaced by the script's own URL and the final
  ``export default`` is dropped, so the file loads as an ordinary script;
- the WebAssembly binary is embedded as base64 and passed as ``wasmBinary``;
- the module is exposed as ``globalThis.KaleidocycleManifold.load()``, which
  resolves to the initialised manifold API (``setup()`` already called).

The package's licence is copied to ``web/vendor/manifold.LICENSE.txt``.

Usage::

    npm pack manifold-3d@3.5.4            # in an empty directory
    tar -xzf manifold-3d-3.5.4.tgz
    python scripts/vendor_manifold.py path/to/package
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "web" / "vendor"

HEADER = """\
/*
 * manifold-3d {version} (Apache-2.0, https://github.com/elalish/manifold),
 * repackaged as a classic script with its WebAssembly module embedded, so that
 * Kaleidocycle Studio can load it from file:// without a server.  Generated by
 * scripts/vendor_manifold.py from the npm package; do not edit.  Licence:
 * manifold.LICENSE.txt.
 */
(function () {{
var __manifoldScriptURL =
  (typeof document !== "undefined" && document.currentScript &&
   document.currentScript.src) || "file:///manifold.js";
"""

FOOTER = """
var WASM_BASE64 = "{wasm}";
function decodeWasm(text) {{
  if (typeof Buffer !== "undefined") return new Uint8Array(Buffer.from(text, "base64"));
  var binary = atob(text);
  var bytes = new Uint8Array(binary.length);
  for (var i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
}}
var ready = null;
globalThis.KaleidocycleManifold = {{
  version: "{version}",
  load: function () {{
    if (!ready) {{
      ready = Module({{
        wasmBinary: decodeWasm(WASM_BASE64),
        locateFile: function (path) {{ return path; }},
      }}).then(function (wasm) {{
        wasm.setup();
        return wasm;
      }});
    }}
    return ready;
  }},
}};
}})();
"""


def build(package: Path) -> Path:
    """Write the classic-script bundle from an extracted npm package."""
    meta = json.loads((package / "package.json").read_text())
    if meta.get("name") != "manifold-3d":
        raise SystemExit(f"{package} is not the manifold-3d package")
    version = meta["version"]
    glue = (package / "manifold.js").read_text()
    if glue.count("import.meta.url") < 1 or not glue.rstrip().endswith(
        "export default Module;"
    ):
        raise SystemExit("unexpected manifold.js layout; check the package version")
    glue = glue.replace("import.meta.url", "__manifoldScriptURL")
    glue = glue.rstrip()[: -len("export default Module;")]
    wasm = base64.b64encode((package / "manifold.wasm").read_bytes()).decode("ascii")

    VENDOR.mkdir(parents=True, exist_ok=True)
    target = VENDOR / "manifold-classic.js"
    footer = FOOTER.format(wasm=wasm, version=version)
    target.write_text(HEADER.format(version=version) + glue + footer)
    licence = (package / "LICENSE").read_text()
    (VENDOR / "manifold.LICENSE.txt").write_text(
        f"manifold-3d {version} (https://github.com/elalish/manifold)\n\n{licence}"
    )
    return target


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("package", type=Path, help="extracted npm package directory")
    target = build(parser.parse_args().package)
    print(f"Wrote {target.relative_to(ROOT)} ({target.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
